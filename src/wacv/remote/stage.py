"""Build a self-contained staging folder for headless remote GPU training.

Shared by every backend under ``src/wacv/remote/``: each one needs the same
``Download -> Train -> Eval -> Visualize -> Package`` pipeline copied onto a
remote machine plus a generated entrypoint that runs it. Stage order and
argv come from ``scripts/export-colab-notebook.py`` (imported, not
re-derived) so the notebook path and every headless backend stay in sync.

The staged folder never includes ``data/`` or credentials - only source code,
the chosen experiment YAML, and a generated ``run_remote.py``. The remote
``Download`` stage re-fetches data the same way the Colab notebook already
does today.

Kaggle *script* kernels keep only ``code_file`` and drop companion files in
the push folder, so ``run_remote.py`` also embeds every staged text file and
materializes them under ``/kaggle/working`` before the first stage runs.
Colab uploads the full tree; materialize is then a no-op overwrite of the
same bytes.
"""

from __future__ import annotations

import importlib.util
import shutil
import sys
from dataclasses import dataclass
from pathlib import Path
from types import ModuleType
from typing import Final

from packaging.requirements import Requirement

ROOT: Final[Path] = Path(__file__).resolve().parents[3]

_ENTRYPOINT_NAME: Final[str] = "run_remote.py"

# Preinstalled on both Kaggle and Colab GPU images; installing our own would
# fight the image CUDA wheel (torch*) or burn PyPI when DNS flaps (numpy…).
_SKIP_PIP_SPECS: Final[frozenset[str]] = frozenset(
    {
        "torch",
        "torchvision",
        "ipykernel",
        "numpy",
        "pillow",
        "pandas",
        "tqdm",
        "matplotlib",
    }
)


def _load_exporter() -> ModuleType:
    """Import ``export-colab-notebook.py`` by path (hyphenated filename)."""
    path = ROOT / "scripts" / "export-colab-notebook.py"
    spec = importlib.util.spec_from_file_location("export_colab_notebook", path)
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load exporter module from {path}")
    module = importlib.util.module_from_spec(spec)
    # dataclasses resolves `cls.__module__` via sys.modules while exec'ing the
    # class body, so the module must be registered before exec_module runs.
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


@dataclass(frozen=True)
class StagingResult:
    """Where the staged folder landed, and the identity it was built for."""

    staging_dir: Path
    run_name: str
    model_name: str
    entrypoint: str = _ENTRYPOINT_NAME


def runtime_pip_specs(root: Path) -> list[str]:
    """Non-preinstalled runtime deps, read from ``pyproject.toml`` itself."""
    import tomllib

    payload = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))
    deps = payload.get("project", {}).get("dependencies", [])
    specs = []
    for spec in deps:
        if Requirement(spec).name not in _SKIP_PIP_SPECS:
            specs.append(spec)
    return specs


def _copy_into(src: Path, root: Path, dest: Path) -> Path:
    """Copy ``src`` under ``dest`` preserving its path relative to ``root``."""
    try:
        rel = src.resolve().relative_to(root.resolve())
    except ValueError as exc:
        raise SystemExit(
            f"{src} is not under the repo root {root}; refusing to stage it"
        ) from exc
    target = dest / rel
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, target)
    return target


def _staged_payload(staging_dir: Path) -> dict[str, str]:
    """POSIX-relpath → utf-8 text for every file under the staging tree.

    Excludes the generated entrypoint (it is rewritten after this snapshot).
    Binary paths (e.g. a vendor wheel tree) are skipped — text materialize
    cannot carry them; pip mirrors cover those deps on the remote.
    """
    payload: dict[str, str] = {}
    for path in sorted(staging_dir.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(staging_dir).as_posix()
        if rel == _ENTRYPOINT_NAME:
            continue
        if rel == "vendor" or rel.startswith("vendor/"):
            continue
        try:
            payload[rel] = path.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            continue
    if "scripts/download-dataset.py" not in payload:
        raise SystemExit(
            "staged payload missing scripts/download-dataset.py - refusing "
            "to emit a broken remote entrypoint"
        )
    return payload


def _entrypoint_source(
    *,
    config_rel: str,
    pip_specs: list[str],
    stages: list[tuple[str, tuple[str, ...]]],
    files: dict[str, str],
) -> str:
    pip_literal = repr(pip_specs)
    stages_literal = "\n".join(f"    {stage!r}," for stage in stages)
    files_literal = repr(files)
    return (
        '"""Auto-generated by src/wacv/remote/stage.py - do not hand-edit.\n\n'
        f"Runs Download -> Train -> Eval -> Visualize -> Package for {config_rel},\n"
        "in the same order scripts/export-colab-notebook.py inlines into the\n"
        "notebook, so the two paths cannot drift apart.\n\n"
        "STAGED_FILES is materialized under /kaggle/working (script kernels\n"
        "drop companions). PIP_INSTALL prefers attached wheel datasets under\n"
        "/kaggle/input (offline, --no-deps so preinstalled torch is enough);\n"
        "network mirrors are used only when no *.whl inputs are attached.\n"
        '"""\n\n'
        "import subprocess\n"
        "import sys\n"
        "import time\n"
        "from pathlib import Path\n\n"
        "SCRIPT_DIR = Path(__file__).resolve().parent\n\n"
        f"PIP_INSTALL = {pip_literal}\n\n"
        f"STAGED_FILES = {files_literal}\n\n"
        f"STAGES = [\n{stages_literal}\n]\n\n\n"
        "def _work_root() -> Path:\n"
        "    # Kaggle script kernels: companions land under /kaggle/working;\n"
        "    # /kaggle/src only has the rewritten code_file.\n"
        "    kaggle_working = Path('/kaggle/working')\n"
        "    if kaggle_working.is_dir():\n"
        "        return kaggle_working\n"
        "    probe = SCRIPT_DIR / '.wacv_write_probe'\n"
        "    try:\n"
        "        probe.write_text('1', encoding='utf-8')\n"
        "        probe.unlink(missing_ok=True)\n"
        "        return SCRIPT_DIR\n"
        "    except OSError:\n"
        "        return Path.cwd()\n\n\n"
        "def _materialize_staged_files(root: Path) -> None:\n"
        "    for rel, content in STAGED_FILES.items():\n"
        "        path = root / rel\n"
        "        path.parent.mkdir(parents=True, exist_ok=True)\n"
        "        path.write_text(content, encoding='utf-8')\n\n\n"
        "def _wheel_dirs() -> list[Path]:\n"
        "    # Any /kaggle/input tree that actually holds *.whl (nested OK).\n"
        "    root = Path('/kaggle/input')\n"
        "    if not root.is_dir():\n"
        "        return []\n"
        "    found: list[Path] = []\n"
        "    for path in sorted(root.rglob('*.whl')):\n"
        "        parent = path.parent\n"
        "        if parent not in found:\n"
        "            found.append(parent)\n"
        "    return found\n\n\n"
        "def _prepend_vendor_paths(root: Path) -> None:\n"
        "    # Optional extracted site-packages: staging vendor/ or input */vendor.\n"
        "    candidates = [root / 'vendor']\n"
        "    input_root = Path('/kaggle/input')\n"
        "    if input_root.is_dir():\n"
        "        candidates.extend(sorted(input_root.glob('*/vendor')))\n"
        "        candidates.extend(sorted(input_root.glob('*/')))\n"
        "    for path in candidates:\n"
        "        if path.is_dir() and (\n"
        "            (path / 'open_clip').is_dir() or (path / 'yaml').is_dir()\n"
        "        ):\n"
        "            inserted = str(path)\n"
        "            if inserted not in sys.path:\n"
        "                sys.path.insert(0, inserted)\n"
        "                print(f'vendor path: {inserted}', flush=True)\n\n\n"
        "def _pip_install(specs: list[str]) -> None:\n"
        "    # Offline wheels first (--no-deps: torch/torchvision stay image-native).\n"
        "    # If any *.whl input is attached, never fall through to the network.\n"
        "    import importlib\n"
        "    import re\n"
        "\n"
        "    import_names = {\n"
        "        'pillow': 'PIL',\n"
        "        'pyyaml': 'yaml',\n"
        "        'open-clip-torch': 'open_clip',\n"
        "        'python-dotenv': 'dotenv',\n"
        "    }\n"
        "\n"
        "    def missing(req_specs: list[str]) -> list[str]:\n"
        "        out: list[str] = []\n"
        "        for spec in req_specs:\n"
        "            name = re.split(\n"
        "                r'[<>=!\\[]', spec, maxsplit=1\n"
        "            )[0].strip().lower()\n"
        "            mod = import_names.get(name, name.replace('-', '_'))\n"
        "            try:\n"
        "                importlib.import_module(mod)\n"
        "            except ImportError:\n"
        "                out.append(spec)\n"
        "        return out\n"
        "\n"
        "    need = missing(specs)\n"
        "    if not need:\n"
        "        return\n"
        "    # open-clip-torch is installed with --no-deps (keep image torch);\n"
        "    # its runtime imports still need these wheels from the same pack.\n"
        "    open_clip_companions = [\n"
        "        'ftfy',\n"
        "        'regex',\n"
        "        'tqdm',\n"
        "        'timm',\n"
        "        'huggingface-hub',\n"
        "        'safetensors',\n"
        "        'wcwidth',\n"
        "        'packaging',\n"
        "        'filelock',\n"
        "        'fsspec',\n"
        "        'typing-extensions',\n"
        "    ]\n"
        "    if any(\n"
        "        re.split(r'[<>=!\\[]', s, maxsplit=1)[0].strip().lower()\n"
        "        == 'open-clip-torch'\n"
        "        for s in need\n"
        "    ):\n"
        "        for companion in open_clip_companions:\n"
        "            if companion not in need and missing([companion]):\n"
        "                need.append(companion)\n"
        "    wheels = _wheel_dirs()\n"
        "    if wheels:\n"
        "        print(\n"
        "            'offline wheels:',\n"
        "            ', '.join(str(w) for w in wheels),\n"
        "            flush=True,\n"
        "        )\n"
        "        # Install one spec at a time with --no-deps so pip does not try\n"
        "        # to fetch torch/etc. from the empty find-links index.\n"
        "        for spec in list(need):\n"
        "            cmd = [\n"
        "                sys.executable,\n"
        "                '-m',\n"
        "                'pip',\n"
        "                'install',\n"
        "                '--no-index',\n"
        "                '--no-deps',\n"
        "            ]\n"
        "            for directory in wheels:\n"
        "                cmd.extend(['--find-links', str(directory)])\n"
        "            cmd.append(spec)\n"
        "            print('offline pip:', ' '.join(cmd), flush=True)\n"
        "            result = subprocess.run(cmd, capture_output=True, text=True)\n"
        "            if result.stdout:\n"
        "                print(result.stdout, end='', flush=True)\n"
        "            if result.returncode != 0:\n"
        "                print(result.stderr, end='', flush=True)\n"
        "                raise SystemExit(\n"
        "                    f'offline pip failed for {spec!r} '\n"
        "                    f'(code={result.returncode}); '\n"
        "                    'refusing network fallback while '\n"
        "                    'wheel inputs are attached'\n"
        "                )\n"
        "        still = missing(specs)\n"
        "        if still:\n"
        "            raise SystemExit(\n"
        "                f'offline pip left imports missing for {still!r}; '\n"
        "                'refusing network fallback while wheel inputs are attached'\n"
        "            )\n"
        "        return\n"
        "    last: subprocess.CompletedProcess[str] | None = None\n"
        "    for attempt in range(8):\n"
        "        failed: list[str] = []\n"
        "        for spec in need:\n"
        "            indexes = [\n"
        "                None,\n"
        "                'https://pypi.tuna.tsinghua.edu.cn/simple',\n"
        "                'https://mirrors.aliyun.com/pypi/simple',\n"
        "            ]\n"
        "            ok = False\n"
        "            for index in indexes:\n"
        "                cmd = [sys.executable, '-m', 'pip', 'install', '-q', spec]\n"
        "                if index is not None:\n"
        "                    host = index.split('/')[2]\n"
        "                    cmd.extend(['-i', index, '--trusted-host', host])\n"
        "                last = subprocess.run(cmd)\n"
        "                if last.returncode == 0:\n"
        "                    ok = True\n"
        "                    break\n"
        "            if not ok:\n"
        "                failed.append(spec)\n"
        "        if not failed:\n"
        "            return\n"
        "        need = failed\n"
        "        time.sleep(min(30 * (2 ** attempt), 300))\n"
        "    code = last.returncode if last else None\n"
        "    raise SystemExit(\n"
        "        f'pip install failed after retries (code={code})'\n"
        "    )\n\n\n"
        "def main() -> None:\n"
        "    root = _work_root()\n"
        "    _materialize_staged_files(root)\n"
        "    _prepend_vendor_paths(root)\n"
        "    if PIP_INSTALL:\n"
        "        _pip_install(PIP_INSTALL)\n"
        "    for script, argv in STAGES:\n"
        "        subprocess.run(\n"
        "            [sys.executable, str(root / script), *argv],\n"
        "            check=True,\n"
        "            cwd=root,\n"
        "        )\n\n\n"
        "if __name__ == '__main__':\n"
        "    main()\n"
    )


def build_staging_dir(config_path: Path, dest: Path) -> StagingResult:
    """Assemble ``dest`` as a standalone copy of the pipeline for one config."""
    exporter = _load_exporter()
    resolved_config = exporter.resolve_path(config_path)
    config_rel = exporter.config_relpath(resolved_config, ROOT)
    identity = exporter.experiment_identity(resolved_config)

    stages = exporter.stages_for_config(config_rel, run_name=identity.run_name)
    visualize = exporter.visualize_stage(config_rel)
    all_stages = [*stages]
    eval_index = next(i for i, s in enumerate(stages) if s.section == "## Eval")
    all_stages.insert(eval_index + 1, visualize)

    entry_scripts = [exporter.resolve_path(stage.script) for stage in all_stages]
    src_files = exporter.collect_src_files(entry_scripts, ROOT)
    if not src_files:
        raise SystemExit("AST walk found no src.wacv modules - refusing empty stage")

    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)

    for script in entry_scripts:
        _copy_into(script, ROOT, dest)
    for src_file in src_files:
        _copy_into(src_file, ROOT, dest)
    for submission_file in exporter.resolved_submission_files():
        _copy_into(submission_file, ROOT, dest)
    _copy_into(resolved_config, ROOT, dest)

    stage_calls = [
        (exporter.rel_posix(exporter.resolve_path(s.script), ROOT), s.argv)
        for s in all_stages
    ]
    payload = _staged_payload(dest)
    entrypoint = dest / _ENTRYPOINT_NAME
    source = _entrypoint_source(
        config_rel=config_rel,
        pip_specs=runtime_pip_specs(ROOT),
        stages=stage_calls,
        files=payload,
    )
    compile(source, str(entrypoint), "exec")  # catch a template bug here, not on a GPU
    entrypoint.write_text(source, encoding="utf-8")

    return StagingResult(
        staging_dir=dest, run_name=identity.run_name, model_name=identity.model_name
    )
