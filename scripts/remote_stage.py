"""Build a self-contained staging folder for headless remote GPU training.

Shared by ``kaggle_train.py`` and ``colab_train.py``: both need the same
``Download -> Train -> Eval -> Visualize -> Package`` pipeline copied onto a
remote machine plus a generated entrypoint that runs it. Stage order and
argv come from ``export-colab-notebook.py`` (imported, not re-derived) so the
notebook path and the two headless paths cannot silently drift apart.

The staged folder never includes ``data/`` or credentials — only source code,
the chosen experiment YAML, and a generated ``run_remote.py``. The remote
``Download`` stage re-fetches data the same way the Colab notebook already
does today.
"""

from __future__ import annotations

import importlib.util
import shutil
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path
from types import ModuleType
from typing import Final

ROOT: Final[Path] = Path(__file__).resolve().parents[1]

# Preinstalled (with a driver-matched build) on both Kaggle and Colab GPU
# images; installing our own would fight the image's own CUDA wheel.
_SKIP_PIP_SPECS: Final[frozenset[str]] = frozenset(
    {"torch", "torchvision", "ipykernel"}
)


def _load_exporter() -> ModuleType:
    """Import ``export-colab-notebook.py`` by path (hyphenated filename)."""
    path = ROOT / "scripts" / "export-colab-notebook.py"
    spec = importlib.util.spec_from_file_location("export_colab_notebook", path)
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load exporter module from {path}")
    module = importlib.util.module_from_spec(spec)
    # dataclasses resolves `cls.__module__` via sys.modules while exec'ing the
    # class body, so the module must be registered before exec_module runs.
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


@dataclass(frozen=True)
class StagingResult:
    """Where the staged folder landed, and the identity it was built for."""

    staging_dir: Path
    run_name: str
    model_name: str
    entrypoint: str = "run_remote.py"


def runtime_pip_specs(root: Path) -> list[str]:
    """Non-preinstalled runtime deps, read from ``pyproject.toml`` itself."""
    payload = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))
    deps = payload.get("project", {}).get("dependencies", [])
    specs = []
    for spec in deps:
        name = spec.split(">=")[0].split("==")[0].split("<")[0].strip()
        if name not in _SKIP_PIP_SPECS:
            specs.append(spec)
    return specs


def _copy_into(src: Path, root: Path, dest: Path) -> None:
    rel = src.resolve().relative_to(root.resolve())
    target = dest / rel
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, target)


def _entrypoint_source(
    *,
    config_rel: str,
    pip_specs: list[str],
    stages: list[tuple[str, tuple[str, ...]]],
) -> str:
    pip_literal = repr(pip_specs)
    stages_literal = "\n".join(f"    {stage!r}," for stage in stages)
    return (
        '"""Auto-generated by scripts/remote_stage.py - do not hand-edit.\n\n'
        f"Runs Download -> Train -> Eval -> Visualize -> Package for {config_rel},\n"
        "in the same order scripts/export-colab-notebook.py inlines into the\n"
        'notebook, so the two paths cannot drift apart.\n"""\n\n'
        "import subprocess\n"
        "import sys\n"
        "from pathlib import Path\n\n"
        "ROOT = Path(__file__).resolve().parent\n\n"
        f"PIP_INSTALL = {pip_literal}\n\n"
        f"STAGES = [\n{stages_literal}\n]\n\n\n"
        "def main() -> None:\n"
        "    if PIP_INSTALL:\n"
        "        subprocess.run(\n"
        "            [sys.executable, '-m', 'pip', 'install', '-q', *PIP_INSTALL],\n"
        "            check=True,\n"
        "        )\n"
        "    for script, argv in STAGES:\n"
        "        subprocess.run(\n"
        "            [sys.executable, str(ROOT / script), *argv],\n"
        "            check=True,\n"
        "            cwd=ROOT,\n"
        "        )\n\n\n"
        "if __name__ == '__main__':\n"
        "    main()\n"
    )


def build_staging_dir(config_path: Path, dest: Path) -> StagingResult:
    """Assemble ``dest`` as a standalone copy of the pipeline for one config."""
    exporter = _load_exporter()
    resolved_config = exporter.resolve_path(config_path)
    config_rel = exporter.config_relpath(resolved_config, ROOT)
    identity = exporter.experiment_identity(resolved_config)

    stages = exporter.stages_for_config(config_rel, run_name=identity.run_name)
    visualize = exporter.visualize_stage(config_rel)
    all_stages = [*stages]
    eval_index = next(i for i, s in enumerate(stages) if s.section == "## Eval")
    all_stages.insert(eval_index + 1, visualize)

    entry_scripts = [exporter.resolve_path(stage.script) for stage in all_stages]
    src_files = exporter.collect_src_files(entry_scripts, ROOT)
    if not src_files:
        raise SystemExit("AST walk found no src.wacv modules - refusing empty stage")

    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)

    for script in entry_scripts:
        _copy_into(script, ROOT, dest)
    for src_file in src_files:
        _copy_into(src_file, ROOT, dest)
    for submission_file in exporter.resolved_submission_files():
        _copy_into(submission_file, ROOT, dest)
    _copy_into(resolved_config, ROOT, dest)

    stage_calls = [
        (exporter.rel_posix(exporter.resolve_path(s.script), ROOT), s.argv)
        for s in all_stages
    ]
    entrypoint = dest / "run_remote.py"
    entrypoint.write_text(
        _entrypoint_source(
            config_rel=config_rel,
            pip_specs=runtime_pip_specs(ROOT),
            stages=stage_calls,
        ),
        encoding="utf-8",
    )

    return StagingResult(
        staging_dir=dest, run_name=identity.run_name, model_name=identity.model_name
    )


if __name__ == "__main__":
    sys.exit(
        "scripts/remote_stage.py is a library; run kaggle_train.py or colab_train.py"
    )
