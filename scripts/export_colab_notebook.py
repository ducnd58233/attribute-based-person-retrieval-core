def notebook_text(notebook: dict[str, object]) -> str:
    """Flatten all cell sources into one searchable string."""
    chunks: list[str] = []
    cells = notebook.get("cells")
    if not isinstance(cells, list):
        return ""
    for cell in cells:
        if not isinstance(cell, dict):
            continue
        source = cell.get("source", [])
        if isinstance(source, list):
            chunks.extend(str(part) for part in source)
        elif isinstance(source, str):
            chunks.append(source)
    return "".join(chunks)


def validate_notebook(path: Path) -> None:
    """Exit non-zero if the notebook fails structural acceptance checks."""
    notebook = json.loads(path.read_text(encoding="utf-8"))
    if notebook.get("nbformat") != NBFORMAT_MAJOR:
        raise SystemExit(
            f"expected nbformat {NBFORMAT_MAJOR}, got {notebook.get('nbformat')}"
        )
    cells = notebook.get("cells")
    if not isinstance(cells, list) or not cells:
        raise SystemExit("notebook has no cells")
    text = notebook_text(notebook)
    missing_sections = [section for section in REQUIRED_SECTIONS if section not in text]
    if missing_sections:
        raise SystemExit(f"missing markdown sections: {missing_sections}")
    missing_scripts = [name for name in REQUIRED_SCRIPTS if name not in text]
    if missing_scripts:
        raise SystemExit(f"notebook does not reference scripts: {missing_scripts}")
    if "Trainer(" in text or "class Trainer" in text:
        raise SystemExit("notebook must not embed a Trainer implementation")
    print(f"check ok: {path} ({len(cells)} cells)")


def write_notebook(path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(build_notebook(), indent=1, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {path}")


def main() -> None:
    args = parse_args()
    # Relative --out is always from the core repo root so callers can invoke
    # this script from any cwd.
    out = args.out if args.out.is_absolute() else (ROOT / args.out).resolve()
    write_notebook(out)
    validate_notebook(out)
    if args.check:
        print("--check passed")


if __name__ == "__main__":
    main()
