"""Generate notebooks/train_pipeline.ipynb from the real pipeline scripts.

Colab and Kaggle are notebook-first GPU hosts. This exporter builds one
notebook whose cells call the existing download/train/evaluate/package
scripts so training logic is not duplicated inside cells.

Usage:
  uv run python scripts/export_colab_notebook.py
  uv run python scripts/export_colab_notebook.py --check
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Final

ROOT: Final[Path] = Path(__file__).resolve().parents[1]
DEFAULT_OUT: Final[Path] = ROOT / "notebooks" / "train_pipeline.ipynb"

REQUIRED_SCRIPTS: Final[tuple[str, ...]] = (
    "download-dataset.py",
    "train.py",
    "evaluate.py",
    "package-submission.py",
)

REQUIRED_SECTIONS: Final[tuple[str, ...]] = (
    "## Download",
    "## Train",
    "## Eval",
    "## Package",
)

NBFORMAT_MAJOR: Final[int] = 4
NBFORMAT_MINOR: Final[int] = 5


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out",
        type=Path,
        default=DEFAULT_OUT,
        help="Destination .ipynb path",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="After writing, assert section markers and script references",
    )
    return parser.parse_args()


def _source_lines(text: str) -> list[str]:
    """Split cell text into nbformat source lines (newline-terminated except last)."""
    body = text.strip("\n")
    if not body:
        return []
    parts = body.split("\n")
    lines = [f"{line}\n" for line in parts[:-1]]
    lines.append(parts[-1])
    return lines


def _md(source: str) -> dict[str, object]:
    return {
        "cell_type": "markdown",
        "metadata": {},
        "source": _source_lines(source),
    }


def _code(source: str) -> dict[str, object]:
    return {
        "cell_type": "code",
        "execution_count": None,
        "metadata": {},
        "outputs": [],
        "source": _source_lines(source),
    }


